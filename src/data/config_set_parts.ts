/**
 * 全部套装部件列表（派生 slots/occupies 后的完整 EquipmentItem）
 *
 * 由 SET_PART_DRAFTS 经 slotRegistry 派生槽位信息：
 * - slots：由 subtype 经 deriveSlots 派生（可装备的候选槽位）
 * - occupies：由 SUBTYPE_OCCUPIES 派生（护甲一部位一槽，无双手武器占用）
 *
 * 全部条目统一使用 SET_MEMBER_CAPABILITIES（含 setMember 能力）。
 */
export const SET_PARTS: EquipmentItem[] = SET_PART_DRAFTS.map(item => ({
  ...item,
  kind: 'equipment' as const,
  stackable: false as const,
  consumable: false as const,
  capabilities: SET_MEMBER_CAPABILITIES,
  slots: deriveSlots(item.subtype),
  occupies: SUBTYPE_OCCUPIES[item.subtype] ?? deriveSlots(item.subtype)
}));