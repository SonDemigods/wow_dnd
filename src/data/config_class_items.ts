/**
 * 根据职业 ID 获取其专属装备列表
 * @param classId - 职业 ID
 * @returns 该职业的专属装备数组
 */
export function getClassSpecificItems(classId: string): EquipmentItem[] {
  return CLASS_SPECIFIC_ITEMS.filter(item =>
    item.classRestriction?.includes(classId)
  );
}
